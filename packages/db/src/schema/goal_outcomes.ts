import { isNotNull, sql } from "drizzle-orm";
import { check, foreignKey, index, integer, jsonb, pgTable, text, timestamp, unique, uniqueIndex, uuid, doublePrecision } from "drizzle-orm/pg-core";
import { companies } from "./companies.js";
import { agents } from "./agents.js";
import { issues } from "./issues.js";
import { goals } from "./goals.js";

export const goalOutcomePeriods = pgTable("goal_outcome_periods", {
  id: uuid("id").primaryKey().defaultRandom(),
  companyId: uuid("company_id").notNull().references(() => companies.id, { onDelete: "cascade" }),
  goalId: uuid("goal_id").notNull(),
  label: text("label").notNull(),
  timezone: text("timezone").notNull(),
  intervalStart: timestamp("interval_start", { withTimezone: true }).notNull(),
  intervalEnd: timestamp("interval_end", { withTimezone: true }).notNull(),
  lifecycle: text("lifecycle").notNull().default("active"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => ({
  goalCompanyFk: foreignKey({ columns: [table.companyId, table.goalId], foreignColumns: [goals.companyId, goals.id], name: "goal_outcome_periods_goal_company_fk" }).onDelete("cascade"),
  intervalCheck: check("goal_outcome_periods_interval_check", sql`${table.intervalEnd} > ${table.intervalStart}`),
  lifecycleCheck: check("goal_outcome_periods_lifecycle_check", sql`${table.lifecycle} in ('draft', 'active', 'closed')`),
  goalCompanyUq: unique("goal_outcome_periods_goal_company_id_uq").on(table.companyId, table.goalId, table.id),
  goalIdx: index("goal_outcome_periods_goal_idx").on(table.goalId, table.intervalStart),
}));

export const goalOutcomeTargets = pgTable("goal_outcome_targets", {
  id: uuid("id").primaryKey().defaultRandom(),
  companyId: uuid("company_id").notNull().references(() => companies.id, { onDelete: "cascade" }),
  goalId: uuid("goal_id").notNull().references(() => goals.id, { onDelete: "cascade" }),
  periodId: uuid("period_id").notNull(),
  metricKey: text("metric_key").notNull(),
  revision: integer("revision").notNull(),
  kind: text("kind").notNull(),
  unit: text("unit").notNull(),
  direction: text("direction").notNull(),
  aggregation: text("aggregation").notNull(),
  population: text("population").notNull(),
  source: text("source").notNull(),
  queryVersion: text("query_version").notNull(),
  freshnessHours: integer("freshness_hours").notNull(),
  maturityHours: integer("maturity_hours").notNull().default(24),
  baselineValue: doublePrecision("baseline_value"),
  targetValue: doublePrecision("target_value"),
  rangeMin: doublePrecision("range_min"),
  rangeMax: doublePrecision("range_max"),
  ownerAgentId: uuid("owner_agent_id"),
  guardrails: jsonb("guardrails").$type<Array<{ name: string; direction: "min" | "max"; threshold: number }>>().notNull().default([]),
  trajectory: jsonb("trajectory").$type<Array<{ at: string; value: number }>>().notNull().default([]),
  approvedBy: text("approved_by").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => ({
  targetOwnerUq: unique("goal_outcome_targets_target_owner_uq").on(table.companyId, table.goalId, table.id),
  periodOwnerFk: foreignKey({ columns: [table.companyId, table.goalId, table.periodId], foreignColumns: [goalOutcomePeriods.companyId, goalOutcomePeriods.goalId, goalOutcomePeriods.id], name: "goal_outcome_targets_period_owner_fk" }),
  ownerCompanyFk: foreignKey({ columns: [table.companyId, table.ownerAgentId], foreignColumns: [agents.companyId, agents.id], name: "goal_outcome_targets_owner_company_fk" }).onDelete("no action"),
  revisionCheck: check("goal_outcome_targets_revision_check", sql`${table.revision} > 0`),
  kindCheck: check("goal_outcome_targets_kind_check", sql`${table.kind} in ('number', 'percentage', 'currency', 'duration', 'count')`),
  directionCheck: check("goal_outcome_targets_direction_check", sql`${table.direction} in ('increase', 'decrease', 'range')`),
  aggregationCheck: check("goal_outcome_targets_aggregation_check", sql`${table.aggregation} in ('latest', 'sum')`),
  freshnessCheck: check("goal_outcome_targets_freshness_check", sql`${table.freshnessHours} > 0`),
  maturityCheck: check("goal_outcome_targets_maturity_check", sql`${table.maturityHours} > 0`),
  rangeCheck: check("goal_outcome_targets_range_check", sql`${table.direction} <> 'range' or (${table.rangeMin} is not null and ${table.rangeMax} is not null and ${table.rangeMin} <= ${table.rangeMax})`),
  revisionUq: unique("goal_outcome_targets_metric_revision_uq").on(table.goalId, table.metricKey, table.revision),
  revisionIdx: index("goal_outcome_targets_period_idx").on(table.periodId, table.metricKey, table.revision),
}));

export const goalOutcomeObservations = pgTable("goal_outcome_observations", {
  id: uuid("id").primaryKey().defaultRandom(),
  companyId: uuid("company_id").notNull().references(() => companies.id, { onDelete: "cascade" }),
  goalId: uuid("goal_id").notNull().references(() => goals.id, { onDelete: "cascade" }),
  targetId: uuid("target_id").notNull(),
  source: text("source").notNull(),
  sourceRevision: text("source_revision").notNull(),
  sourceKey: text("source_key").notNull(),
  value: doublePrecision("value").notNull(),
  unit: text("unit").notNull(),
  population: text("population").notNull(),
  windowStart: timestamp("window_start", { withTimezone: true }).notNull(),
  windowEnd: timestamp("window_end", { withTimezone: true }).notNull(),
  observedAt: timestamp("observed_at", { withTimezone: true }).notNull(),
  availableAt: timestamp("available_at", { withTimezone: true }).notNull().defaultNow(),
  ingestedAt: timestamp("ingested_at", { withTimezone: true }).notNull().defaultNow(),
  valid: text("valid").notNull().default("true"),
  submittedBy: text("submitted_by").notNull(),
  submitterType: text("submitter_type").notNull(),
  submitterSource: text("submitter_source").notNull(),
  submitterKeyId: uuid("submitter_key_id"),
  runId: uuid("run_id"),
  guardrailValues: jsonb("guardrail_values").$type<Record<string, number>>().notNull().default({}),
  supersedesId: uuid("supersedes_id"),
  correctionReason: text("correction_reason"),
}, (table) => ({
  windowCheck: check("goal_outcome_observations_window_check", sql`${table.windowEnd} > ${table.windowStart}`),
  availabilityCheck: check("goal_outcome_observations_availability_check", sql`${table.availableAt} >= ${table.observedAt}`),
  correctionReasonCheck: check("goal_outcome_observations_correction_reason_check", sql`${table.supersedesId} is null or (${table.correctionReason} is not null and length(trim(${table.correctionReason})) > 0)`),
  validityCheck: check("goal_outcome_observations_valid_check", sql`${table.valid} in ('true', 'false')`),
  targetOwnerUq: unique("goal_outcome_observations_target_owner_uq").on(table.companyId, table.goalId, table.targetId, table.id),
  submitterTypeCheck: check("goal_outcome_observations_submitter_type_check", sql`${table.submitterType} in ('agent', 'user')`),
  targetOwnerFk: foreignKey({ columns: [table.companyId, table.goalId, table.targetId], foreignColumns: [goalOutcomeTargets.companyId, goalOutcomeTargets.goalId, goalOutcomeTargets.id], name: "goal_outcome_observations_target_owner_fk" }),
  supersedesOwnerFk: foreignKey({ columns: [table.companyId, table.goalId, table.targetId, table.supersedesId], foreignColumns: [table.companyId, table.goalId, table.targetId, table.id], name: "goal_outcome_observations_supersedes_owner_fk" }),
  dedupeUq: unique("goal_outcome_observations_source_key_uq").on(table.targetId, table.source, table.sourceKey),
  correctionUq: uniqueIndex("goal_outcome_observations_correction_uq").on(table.supersedesId).where(isNotNull(table.supersedesId)),
  targetObservedIdx: index("goal_outcome_observations_target_observed_idx").on(table.targetId, table.observedAt),
}));

export const goalOutcomeCheckins = pgTable("goal_outcome_checkins", {
  id: uuid("id").primaryKey().defaultRandom(),
  companyId: uuid("company_id").notNull().references(() => companies.id, { onDelete: "cascade" }),
  goalId: uuid("goal_id").notNull().references(() => goals.id, { onDelete: "cascade" }),
  targetId: uuid("target_id").notNull(),
  health: text("health").notNull(),
  evidence: text("evidence").notNull(),
  forecastValue: doublePrecision("forecast_value"),
  uncertainty: text("uncertainty").notNull(),
  correctiveIssueId: uuid("corrective_issue_id"),
  nextReviewAt: timestamp("next_review_at", { withTimezone: true }).notNull(),
  createdBy: text("created_by").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => ({
  healthCheck: check("goal_outcome_checkins_health_check", sql`${table.health} in ('on_track', 'at_risk', 'off_track', 'unknown')`),
  targetOwnerFk: foreignKey({ columns: [table.companyId, table.goalId, table.targetId], foreignColumns: [goalOutcomeTargets.companyId, goalOutcomeTargets.goalId, goalOutcomeTargets.id], name: "goal_outcome_checkins_target_owner_fk" }),
  correctiveIssueCompanyFk: foreignKey({ columns: [table.companyId, table.correctiveIssueId], foreignColumns: [issues.companyId, issues.id], name: "goal_outcome_checkins_corrective_issue_company_fk" }).onDelete("no action"),
  goalCreatedIdx: index("goal_outcome_checkins_goal_idx").on(table.goalId, table.createdAt),
}));
